#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
cd "${REPO_ROOT}"

SYNC_MODE=${1:-off}
case "${SYNC_MODE}" in
  off|0|false|FALSE)
    export QWEN_IMAGE_STAGE_TIMING_SYNC=0
    SYNC_LABEL=sync_off
    ;;
  on|1|true|TRUE)
    export QWEN_IMAGE_STAGE_TIMING_SYNC=1
    SYNC_LABEL=sync_on
    ;;
  *)
    echo "Usage: $0 [off|on]" >&2
    exit 2
    ;;
esac

TIMESTAMP=${QWEN_IMAGE_STAGE_PIPELINE_TIMESTAMP:-$(date +%Y%m%d-%H%M%S)}
OUTDIR=${QWEN_IMAGE_STAGE_PIPELINE_SMOKE_OUTDIR:-"${REPO_ROOT}/benchmark_outputs/codex-qwen-image-stage-realistic-timing-${SYNC_LABEL}-${TIMESTAMP}"}
LATEST=${QWEN_IMAGE_STAGE_PIPELINE_LATEST:-"${REPO_ROOT}/benchmark_outputs/codex-qwen-image-stage-realistic-timing-${SYNC_LABEL}.latest"}
mkdir -p "$(dirname "${OUTDIR}")" "$(dirname "${LATEST}")"

export QWEN_IMAGE_STAGE_PIPELINE_CONFIG=${QWEN_IMAGE_STAGE_PIPELINE_CONFIG:-"${REPO_ROOT}/vllm_omni/deploy/qwen_image_stage_pipeline.yaml"}
export QWEN_IMAGE_STAGE_PIPELINE_SMOKE_OUTDIR="${OUTDIR}"
export QWEN_IMAGE_STAGE_PIPELINE_REQUESTS=${QWEN_IMAGE_STAGE_PIPELINE_REQUESTS:-1}
export QWEN_IMAGE_STAGE_PIPELINE_WARMUP_REQUESTS=${QWEN_IMAGE_STAGE_PIPELINE_WARMUP_REQUESTS:-1}
export QWEN_IMAGE_STAGE_PIPELINE_STAGGER_S=${QWEN_IMAGE_STAGE_PIPELINE_STAGGER_S:-0}
export QWEN_IMAGE_STAGE_PIPELINE_HEIGHT=${QWEN_IMAGE_STAGE_PIPELINE_HEIGHT:-1024}
export QWEN_IMAGE_STAGE_PIPELINE_WIDTH=${QWEN_IMAGE_STAGE_PIPELINE_WIDTH:-1024}
export QWEN_IMAGE_STAGE_PIPELINE_STEPS_LIST=${QWEN_IMAGE_STAGE_PIPELINE_STEPS_LIST:-4,8,12}
export QWEN_IMAGE_STAGE_PIPELINE_TRUE_CFG_SCALE=${QWEN_IMAGE_STAGE_PIPELINE_TRUE_CFG_SCALE:-2.0}
export QWEN_IMAGE_STAGE_PIPELINE_REQUIRE_TRACE=${QWEN_IMAGE_STAGE_PIPELINE_REQUIRE_TRACE:-1}
export QWEN_IMAGE_STAGE_PIPELINE_LB_POLICY=${QWEN_IMAGE_STAGE_PIPELINE_LB_POLICY:-round-robin}
export QWEN_IMAGE_STAGE_FINE_TIMING=${QWEN_IMAGE_STAGE_FINE_TIMING:-1}

export ASCEND_RT_VISIBLE_DEVICES=${ASCEND_RT_VISIBLE_DEVICES:-0,1,2}
export QUANTIZATION_CONFIG=${QUANTIZATION_CONFIG:-'"int8"'}
export PR4024_DYNAMIC_ATTENTION_BACKEND=${PR4024_DYNAMIC_ATTENTION_BACKEND:-FLASH_ATTN}
export MINDIE_SD_FA_TYPE=${MINDIE_SD_FA_TYPE:-ascend_laser_attention}
unset VLLM_USE_MODELSCOPE

ln -sfn "${OUTDIR}" "${LATEST}"
python benchmarks/diffusion/run_qwen_image_stage_pipeline_smoke.py
